'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const engine=require('../assets/surebet-calculations.js');
const html=fs.readFileSync('index.html','utf8');
assert(html.includes('data-view="surebets"')&&html.includes('id="view-surebets"'),'Surebet navigation must exist');
assert(html.includes('/assets/surebets-ui.js')&&html.includes('/assets/surebet-calculations.js'));
const now=Date.now();
const event={event_id:'fixture01',league:'E0',home:'Home FC',away:'Away FC',kickoff_at:new Date(now+86400000).toISOString(),collected_at:new Date(now-60000).toISOString(),source_updated_at:new Date(now-70000).toISOString(),description:'',line:null};
const q=(outcome,bookmaker_key,decimal_odds,market='full_time_result',extra={})=>({...event,market,outcome,bookmaker_key,bookmaker:bookmaker_key,decimal_odds,...extra});
let rows=[q('H','a',2.2),q('D','b',3.8),q('A','c',4.6)];
const result=engine.scan(rows,{now,stake:100});
assert.equal(result.length,1,'Complete profitable three-way market qualifies');
assert.equal(result[0].fresh,true);
assert.equal(result[0].legs.length,3);
assert.equal(result[0].legs.reduce((v,x)=>v+Math.round(x.stake*100),0),10000,'Stakes must sum exactly to budget');
assert(result[0].profit>0&&result[0].roiPct>0);
assert.equal(engine.scan(rows.slice(0,2),{now}).length,0,'Missing away outcome rejects arbitrage');
assert.equal(engine.scan(rows.map(x=>({...x,bookmaker_key:'same'})),{now}).length,0,'Multiple bookmakers are required');
assert.equal(engine.scan([q('H','a',2),q('D','b',3),q('A','c',4)],{now}).length,0,'Nonprofitable set rejected');
assert.equal(engine.scan([...rows,q('H','x',2.5,{})],{now}).length,1,'Extra inferior quotes may be ignored');
const stale=engine.scan(rows.map(x=>({...x,collected_at:new Date(now-3600000).toISOString(),source_updated_at:new Date(now-3610000).toISOString()})),{now});
assert.equal(stale.length,1);assert.equal(stale[0].fresh,false,'Old prices must never be live');
const farApart=rows.map((x,i)=>({...x,collected_at:new Date(now-i*300000).toISOString(),source_updated_at:new Date(now-i*300000-10000).toISOString()}));
assert.equal(engine.scan(farApart,{now}).length,0,'Mixed snapshot ages rejected');
const total=[q('Over','a',2.35,'goals_total',{line:2.5}),q('Under','b',2.35,'goals_total',{line:2.5})];
assert.equal(engine.scan(total,{now}).length,1,'Same 2.5 goal line allowed');
assert.equal(engine.scan([total[0],{...total[1],line:3.5}],{now}).length,0,'Different goal lines cannot combine');
const corners=[q('Over','a',2.2,'alternate_totals_corners',{line:10.5}),q('Under','b',2.2,'alternate_totals_corners',{line:10.5})];
assert.equal(engine.scan(corners,{now}).length,1);
assert.equal(engine.scan(corners.map(x=>({...x,line:10})),{now}).length,0,'Push-capable integer lines excluded');
assert.equal(engine.scan([...corners.slice(0,1),{...corners[1],description:'Home FC'}],{now}).length,0,'Different team markets cannot mix');
const btts=[q('Yes','a',2.3,'btts'),q('No','b',2.3,'btts')];
assert.equal(engine.scan(btts,{now}).length,1);
const half=[q('Home FC','a',2.3,'h2h_3_way_h1'),q('Draw','b',3.8,'h2h_3_way_h1'),q('Away FC','c',5,'h2h_3_way_h1')];
assert.equal(engine.scan(half,{now}).length,1);
const labels=['Home FC','Draw','Away FC'];
const hft=labels.flatMap((x,i)=>labels.map((y,j)=>q(x+'/'+y,'book'+(i+j),15,'halftime_fulltime')));
assert.equal(engine.scan(hft,{now}).length,1,'All nine halftime/fulltime outcomes qualify');
assert.equal(engine.scan(hft.slice(1),{now}).length,0,'Nine-way market requires all outcomes');
const insufficient=engine.allocate(rows.map(x=>engine.normalize(x)),1);
assert(insufficient&&insufficient.legs.reduce((s,x)=>s+Math.round(x.stake*100),0)===100);
assert(Number.isFinite(insufficient.profit));
const url=html.match(/const CLOUD_URL='([^']+)'/)?.[1],key=html.match(/const CLOUD_KEY='([^']+)'/)?.[1];
assert(url&&key,'Cloud client configuration');
(async()=>{
 const endpoint=url+'/functions/v1/gerball-surebets';
 const rejected=await fetch(endpoint,{signal:AbortSignal.timeout(20000)});
 assert.equal(rejected.status,401,'Public requests without application key must be rejected');
 const rejectedPost=await fetch(endpoint,{method:'POST',headers:{apikey:key},signal:AbortSignal.timeout(20000)});
 assert.equal(rejectedPost.status,405,'Feed must be GET only');
 const response=await fetch(endpoint,{headers:{apikey:key},signal:AbortSignal.timeout(25000)});
 assert.equal(response.status,200,'Surebet price feed must be operational');
 const data=await response.json();
 assert.equal(data.version,'surebet_feed_v1');
 assert(Array.isArray(data.quotes));
 assert(data.quotes.length<=6000);
 assert.equal(data.quotes.length,data.complete_market_quote_rows);
 assert(data.quotes.every(x=>x.bookmaker_key!=='betfair_ex_uk'&&x.bookmaker_key!=='smarkets'&&x.bookmaker_key!=='matchbook'),'Exchange commissions unknown');
 assert(data.refresh&&['completed','failed','claimed'].includes(data.refresh.status),'Refresh provenance must be present');
 assert(Number.isInteger(data.refresh.daily_request_count)&&data.refresh.daily_request_count<=28,'Daily requests capped');
 assert(Number.isInteger(data.refresh.daily_credits_used)&&data.refresh.daily_credits_used<=35,'Daily API credits reserved');
 assert(data.refresh.stored_quotes>=0&&data.refresh.provider_cost>=0);
 const refreshEndpoint=url+'/functions/v1/gerball-surebet-refresh';
 const noGet=await fetch(refreshEndpoint,{signal:AbortSignal.timeout(15000)});
 assert.equal(noGet.status,405,'Refresh collector is POST-only');
 const noToken=await fetch(refreshEndpoint,{method:'POST',headers:{'content-type':'application/json'},body:'{"mode":"scheduled"}',signal:AbortSignal.timeout(15000)});
 assert.equal(noToken.status,401,'Refresh cannot spend quota without private token');
 const source=fs.readFileSync('supabase/surebet-scanner-source.sql','utf8');
 assert(source.includes('gerball_surebet_private.refresh_quotes'),'Feed must include sampled refresh prices');
 assert(source.includes("n.newest-interval '2 minutes'"),'Feed must isolate synchronized price snapshots');
 const opportunities=engine.scan(data.quotes,{stake:100,now:Date.now()});
 assert(opportunities.every(x=>x.profit>0&&x.implied<1&&x.bookmakers>1));
 console.log('Surebet scanner verified:',data.quotes.length,'best-price legs,',opportunities.filter(x=>x.fresh).length,'fresh surebets,',opportunities.filter(x=>!x.fresh).length,'older theoretical.');
})().catch(error=>{console.error(error);process.exitCode=1});
