-- Immutable observations of the existing historical form screen.
-- This is an unpriced research ledger. Existing predictions, approvals, importers
-- and odds collection are neither read nor changed by this migration.
CREATE SCHEMA gerball_tracking_private;
REVOKE ALL ON SCHEMA gerball_tracking_private FROM PUBLIC, anon, authenticated, service_role;
GRANT USAGE ON SCHEMA gerball_tracking_private TO service_role;

CREATE TABLE gerball_tracking_private.rule_versions (
  version text PRIMARY KEY,
  frozen_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  implementation_sha256 text NOT NULL CHECK (implementation_sha256 ~ '^[a-f0-9]{64}$'),
  source_commit text NOT NULL,
  evaluation_start date NOT NULL,
  specification jsonb NOT NULL CHECK (jsonb_typeof(specification) = 'object')
);

CREATE TABLE gerball_tracking_private.cohorts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule_version text NOT NULL REFERENCES gerball_tracking_private.rule_versions(version),
  league_code text NOT NULL,
  capture_date date NOT NULL,
  captured_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  collection_date date NOT NULL,
  collection_checked_at timestamptz NOT NULL,
  collection_status text NOT NULL CHECK (collection_status IN ('completed','inactive')),
  source_fixture_count integer NOT NULL CHECK (source_fixture_count BETWEEN 0 AND 1000),
  fixture_count integer NOT NULL CHECK (fixture_count BETWEEN 0 AND 1000),
  skipped_started integer NOT NULL CHECK (skipped_started >= 0),
  mode text NOT NULL CHECK (mode IN ('scheduled','bootstrap')),
  input_sha256 text NOT NULL CHECK (input_sha256 ~ '^[a-f0-9]{64}$'),
  UNIQUE (rule_version, league_code, capture_date),
  UNIQUE (id, rule_version, league_code),
  CHECK (collection_date = capture_date),
  CHECK (collection_checked_at <= captured_at),
  CHECK (collection_status <> 'inactive' OR fixture_count = 0),
  CHECK (source_fixture_count = fixture_count + skipped_started)
);

CREATE TABLE gerball_tracking_private.observations (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  cohort_id bigint NOT NULL,
  rule_version text NOT NULL,
  league_code text NOT NULL,
  event_id text NOT NULL CHECK (length(event_id) BETWEEN 1 AND 200),
  recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  kickoff_at timestamptz NOT NULL,
  fixture_date date NOT NULL,
  season text NOT NULL CHECK (season ~ '^[0-9]{4}$'),
  phase text NOT NULL CHECK (phase IN ('calibration','post_boundary')),
  fixture jsonb NOT NULL CHECK (jsonb_typeof(fixture) = 'object'),
  input_sha256 text NOT NULL CHECK (input_sha256 ~ '^[a-f0-9]{64}$'),
  FOREIGN KEY (cohort_id, rule_version, league_code)
    REFERENCES gerball_tracking_private.cohorts(id, rule_version, league_code)
    DEFERRABLE INITIALLY DEFERRED,
  UNIQUE (cohort_id, event_id),
  CHECK (recorded_at < kickoff_at)
);
CREATE INDEX gerball_tracking_observation_event_idx
  ON gerball_tracking_private.observations(rule_version, league_code, event_id, recorded_at, id);
CREATE INDEX gerball_tracking_observation_kickoff_idx
  ON gerball_tracking_private.observations(kickoff_at, id);

CREATE TABLE gerball_tracking_private.result_revisions (
  observation_id bigint NOT NULL REFERENCES gerball_tracking_private.observations(id),
  revision integer NOT NULL CHECK (revision >= 1),
  recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  status text NOT NULL CHECK (status IN ('pending','settled','review')),
  reason text NOT NULL,
  match_id bigint,
  source text,
  imported_at timestamptz,
  home_goals integer,
  away_goals integer,
  full_time_result text,
  result_sha256 text NOT NULL CHECK (result_sha256 ~ '^[a-f0-9]{64}$'),
  correction_reason text,
  PRIMARY KEY (observation_id, revision),
  CHECK (status <> 'settled' OR (
    match_id IS NOT NULL AND source IS NOT NULL AND source = 'football-data.co.uk' AND imported_at IS NOT NULL
    AND home_goals IS NOT NULL AND away_goals IS NOT NULL AND full_time_result IS NOT NULL
    AND home_goals >= 0 AND away_goals >= 0
    AND full_time_result = CASE WHEN home_goals > away_goals THEN 'H'
      WHEN home_goals < away_goals THEN 'A' ELSE 'D' END)),
  CHECK (revision = 1 OR (correction_reason IS NOT NULL AND length(btrim(correction_reason)) > 0))
);

CREATE TABLE gerball_tracking_private.operation_runs (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  operation text NOT NULL CHECK (operation IN ('capture','reconcile')),
  recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  operation_date date NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'Europe/London')::date,
  details jsonb NOT NULL
);
CREATE INDEX gerball_tracking_operation_recent_idx
  ON gerball_tracking_private.operation_runs(operation, recorded_at DESC);

ALTER TABLE gerball_tracking_private.rule_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE gerball_tracking_private.cohorts ENABLE ROW LEVEL SECURITY;
ALTER TABLE gerball_tracking_private.observations ENABLE ROW LEVEL SECURITY;
ALTER TABLE gerball_tracking_private.result_revisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE gerball_tracking_private.operation_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA gerball_tracking_private FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA gerball_tracking_private FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON ALL TABLES IN SCHEMA gerball_tracking_private TO service_role;

