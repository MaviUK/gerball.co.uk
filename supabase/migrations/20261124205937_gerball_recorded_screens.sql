CREATE FUNCTION gerball_tracking_private.reject_mutation()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
BEGIN
  RAISE EXCEPTION 'recorded_screen_rows_are_append_only' USING ERRCODE = '55000';
END
$function$;

CREATE FUNCTION gerball_tracking_private.stamp_observation()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_boundary date;
  v_specification jsonb;
  v_cutoff date;
BEGIN
  -- A cohort is inserted only after all its observations, sealing the set.
  IF EXISTS (SELECT 1 FROM gerball_tracking_private.cohorts WHERE id = NEW.cohort_id) THEN
    RAISE EXCEPTION 'recorded_screen_cohort_is_sealed' USING ERRCODE = '55000';
  END IF;
  SELECT evaluation_start,specification INTO STRICT v_boundary,v_specification
    FROM gerball_tracking_private.rule_versions WHERE version = NEW.rule_version;
  NEW.recorded_at := clock_timestamp();
  NEW.event_id := NEW.fixture->>'event_id';
  NEW.league_code := NEW.fixture->>'league_code';
  NEW.kickoff_at := (NEW.fixture->>'kickoff_at')::timestamptz;
  IF NEW.kickoff_at IS NULL OR NEW.kickoff_at <= NEW.recorded_at THEN
    RAISE EXCEPTION 'recording_after_kickoff' USING ERRCODE = '22023';
  END IF;
  IF NOT COALESCE(v_specification->'leagues' ? NEW.league_code,false)
    OR NEW.kickoff_at > ((NEW.recorded_at AT TIME ZONE 'Europe/London') + interval '14 days') AT TIME ZONE 'Europe/London' THEN
    RAISE EXCEPTION 'invalid_recorded_screen_scope' USING ERRCODE = '22023';
  END IF;
  NEW.fixture_date := (NEW.kickoff_at AT TIME ZONE 'Europe/London')::date;
  NEW.season := to_char(NEW.fixture_date - interval '6 months', 'YY')
    || to_char(NEW.fixture_date + interval '6 months', 'YY');
  NEW.phase := CASE WHEN NEW.fixture_date < v_boundary THEN 'calibration' ELSE 'post_boundary' END;
  v_cutoff := (NEW.fixture->>'cutoff_date')::date;
  IF v_cutoff IS NULL OR v_cutoff >= NEW.fixture_date
    OR v_cutoff > (NEW.recorded_at AT TIME ZONE 'Europe/London')::date
    OR jsonb_typeof(NEW.fixture->'markets') IS DISTINCT FROM 'object'
    OR NOT (NEW.fixture->'markets' ?& ARRAY['H','D','A'])
    OR EXISTS (SELECT 1 FROM jsonb_each(NEW.fixture->'markets') AS m
      WHERE m.key NOT IN ('H','D','A') OR m.value->>'status' IS NULL OR m.value->>'status' NOT IN
        ('match','no_match','insufficient_history','unmatched_team')
      OR jsonb_typeof(m.value->'status') IS DISTINCT FROM 'string'
      OR jsonb_typeof(m.value->'reason') IS DISTINCT FROM 'string')
    OR EXISTS (SELECT 1 FROM (VALUES ('home'::text),('away'::text)) AS s(side)
      WHERE jsonb_typeof(NEW.fixture->s.side->'provider_name') IS DISTINCT FROM 'string'
        OR length(btrim(NEW.fixture->s.side->>'provider_name')) = 0
        OR jsonb_typeof(NEW.fixture->s.side->'history'->'dates') IS DISTINCT FROM 'array'
        OR jsonb_array_length(NEW.fixture->s.side->'history'->'dates') > 5)
    OR EXISTS (SELECT 1 FROM (VALUES ('home'::text),('away'::text)) AS s(side)
      CROSS JOIN LATERAL jsonb_array_elements(NEW.fixture->s.side->'history'->'dates') AS d
      WHERE jsonb_typeof(d->'date') IS DISTINCT FROM 'string'
        OR (d->>'date') !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
        OR (d->>'date')::date > v_cutoff) THEN
    RAISE EXCEPTION 'invalid_recorded_screen_snapshot' USING ERRCODE = '22023';
  END IF;
  NEW.input_sha256 := encode(extensions.digest(jsonb_build_object(
    'rule_version', NEW.rule_version, 'fixture', NEW.fixture)::text, 'sha256'), 'hex');
  RETURN NEW;
END
$function$;

CREATE FUNCTION gerball_tracking_private.seal_cohort()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_inputs jsonb;
BEGIN
  NEW.captured_at := clock_timestamp();
  NEW.capture_date := (NEW.captured_at AT TIME ZONE 'Europe/London')::date;
  SELECT count(*)::integer, COALESCE(jsonb_agg(o.input_sha256 ORDER BY o.event_id), '[]'::jsonb)
    INTO NEW.fixture_count, v_inputs
  FROM gerball_tracking_private.observations AS o WHERE o.cohort_id = NEW.id;
  IF EXISTS (SELECT 1 FROM gerball_tracking_private.observations AS o
      WHERE o.cohort_id = NEW.id AND ((o.recorded_at AT TIME ZONE 'Europe/London')::date <> NEW.capture_date
        OR o.rule_version <> NEW.rule_version OR o.league_code <> NEW.league_code)) THEN
    RAISE EXCEPTION 'recorded_screen_cohort_mismatch' USING ERRCODE = '22023';
  END IF;
  NEW.skipped_started := NEW.source_fixture_count - NEW.fixture_count;
  NEW.input_sha256 := encode(extensions.digest(jsonb_build_object(
    'rule_version', NEW.rule_version, 'league_code', NEW.league_code,
    'capture_date', NEW.capture_date, 'collection_date', NEW.collection_date,
    'collection_checked_at', NEW.collection_checked_at, 'collection_status', NEW.collection_status,
    'source_fixture_count', NEW.source_fixture_count, 'inputs', v_inputs)::text, 'sha256'), 'hex');
  RETURN NEW;
END
$function$;

CREATE FUNCTION gerball_tracking_private.stamp_result()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_observation gerball_tracking_private.observations%ROWTYPE;
  v_last gerball_tracking_private.result_revisions%ROWTYPE;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('gerball-tracking-result:' || NEW.observation_id::text, 0));
  SELECT * INTO STRICT v_observation FROM gerball_tracking_private.observations WHERE id = NEW.observation_id;
  NEW.recorded_at := clock_timestamp();
  IF NEW.recorded_at < v_observation.kickoff_at + interval '3 hours' THEN
    RAISE EXCEPTION 'recorded_screen_result_too_early' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_last FROM gerball_tracking_private.result_revisions
    WHERE observation_id = NEW.observation_id ORDER BY revision DESC LIMIT 1;
  NEW.revision := COALESCE(v_last.revision, 0) + 1;
  NEW.result_sha256 := encode(extensions.digest(jsonb_build_object(
    'status', NEW.status, 'reason', NEW.reason, 'match_id', NEW.match_id, 'source', NEW.source,
    'home_goals', NEW.home_goals, 'away_goals', NEW.away_goals,
    'full_time_result', NEW.full_time_result)::text, 'sha256'), 'hex');
  IF NEW.result_sha256 = v_last.result_sha256 THEN
    RAISE EXCEPTION 'duplicate_recorded_screen_result' USING ERRCODE = '23505';
  END IF;
  IF NEW.status = 'settled' AND NEW.imported_at <= v_observation.recorded_at THEN
    RAISE EXCEPTION 'result_predates_capture' USING ERRCODE = '22023';
  END IF;
  RETURN NEW;
END
$function$;

CREATE FUNCTION gerball_tracking_private.stamp_operation()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
BEGIN
  NEW.recorded_at := clock_timestamp();
  NEW.operation_date := (NEW.recorded_at AT TIME ZONE 'Europe/London')::date;
  RETURN NEW;
END
$function$;

CREATE TRIGGER recorded_screen_observation_stamp BEFORE INSERT ON gerball_tracking_private.observations
  FOR EACH ROW EXECUTE FUNCTION gerball_tracking_private.stamp_observation();
CREATE TRIGGER recorded_screen_cohort_seal BEFORE INSERT ON gerball_tracking_private.cohorts
  FOR EACH ROW EXECUTE FUNCTION gerball_tracking_private.seal_cohort();
CREATE TRIGGER recorded_screen_result_stamp BEFORE INSERT ON gerball_tracking_private.result_revisions
  FOR EACH ROW EXECUTE FUNCTION gerball_tracking_private.stamp_result();
CREATE TRIGGER recorded_screen_operation_stamp BEFORE INSERT ON gerball_tracking_private.operation_runs
  FOR EACH ROW EXECUTE FUNCTION gerball_tracking_private.stamp_operation();

DO $triggers$
DECLARE v_table text;
BEGIN
  FOREACH v_table IN ARRAY ARRAY['rule_versions','cohorts','observations','result_revisions','operation_runs'] LOOP
    EXECUTE format('CREATE TRIGGER recorded_screen_immutable BEFORE UPDATE OR DELETE ON gerball_tracking_private.%I FOR EACH ROW EXECUTE FUNCTION gerball_tracking_private.reject_mutation()', v_table);
  END LOOP;
END
$triggers$;

CREATE FUNCTION gerball_tracking_private.capture_league(p_league text, p_mode text DEFAULT 'scheduled')
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_rule gerball_tracking_private.rule_versions%ROWTYPE;
  v_today date := (clock_timestamp() AT TIME ZONE 'Europe/London')::date;
  v_sport text;
  v_collection public.gerball_odds_league_runs%ROWTYPE;
  v_parent_status text;
  v_existing bigint;
  v_id bigint;
  v_screen jsonb;
  v_fixture jsonb;
  v_fixture_count integer;
BEGIN
  SELECT * INTO STRICT v_rule FROM gerball_tracking_private.rule_versions WHERE version = 'ppg_last5_dates_050_v1';
  v_sport := v_rule.specification->'leagues'->>p_league;
  IF v_sport IS NULL OR p_mode IS NULL OR p_mode NOT IN ('scheduled','bootstrap') THEN
    RAISE EXCEPTION 'invalid_capture_parameters' USING ERRCODE = '22023';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('gerball-tracking-capture:' || v_today::text || ':' || p_league, 0));
  SELECT id INTO v_existing FROM gerball_tracking_private.cohorts
    WHERE rule_version = v_rule.version AND league_code = p_league AND capture_date = v_today;
  IF FOUND THEN
    RETURN jsonb_build_object('league_code', p_league, 'status', 'already_recorded', 'cohort_id', v_existing);
  END IF;
  IF gerball_tracking_private.implementation_hash() <> v_rule.implementation_sha256 THEN
    RETURN jsonb_build_object('league_code', p_league, 'status', 'implementation_changed', 'reason', 'Frozen rule implementation no longer matches.');
  END IF;
  SELECT * INTO v_collection FROM public.gerball_odds_league_runs
    WHERE collection_date = v_today AND sport_key = v_sport;
  SELECT status INTO v_parent_status FROM public.gerball_odds_runs WHERE collection_date = v_today;
  IF v_collection.status IS NULL OR v_collection.status NOT IN ('completed','inactive')
    OR v_parent_status IS NULL OR v_parent_status NOT IN ('completed','partial') THEN
    RETURN jsonb_build_object('league_code', p_league, 'status', 'waiting_for_collection',
      'reason', 'A completed same-day league collection is required.');
  END IF;
  IF v_collection.status = 'inactive' THEN
    v_screen := jsonb_build_object('version', v_rule.version, 'fixtures', '[]'::jsonb);
  ELSE
    v_screen := public.gerball_strategy_screen(p_league, 14);
    IF v_screen->>'version' IS DISTINCT FROM v_rule.version
      OR (v_screen#>>'{collection,collection_date}')::date IS DISTINCT FROM v_today
      OR v_screen#>'{rules,qualification_uses_current_odds}' IS DISTINCT FROM 'false'::jsonb THEN
      RAISE EXCEPTION 'recorded_screen_source_mismatch' USING ERRCODE = '22023';
    END IF;
  END IF;
  v_fixture_count := jsonb_array_length(v_screen->'fixtures');
  IF v_fixture_count > 1000 THEN RAISE EXCEPTION 'recorded_screen_fixture_limit' USING ERRCODE = '22023'; END IF;
  v_id := nextval(pg_get_serial_sequence('gerball_tracking_private.cohorts', 'id'));
  FOR v_fixture IN SELECT value FROM jsonb_array_elements(v_screen->'fixtures') LOOP
    IF (v_fixture->>'kickoff_at')::timestamptz > clock_timestamp() THEN
      BEGIN
        INSERT INTO gerball_tracking_private.observations
          (cohort_id, rule_version, league_code, event_id, kickoff_at, fixture_date, season, phase, fixture, input_sha256)
        VALUES (v_id, v_rule.version, p_league, v_fixture->>'event_id',
          (v_fixture->>'kickoff_at')::timestamptz, v_today, '0000', 'calibration', v_fixture, repeat('0',64));
      EXCEPTION WHEN invalid_parameter_value THEN
        IF SQLERRM <> 'recording_after_kickoff' THEN RAISE; END IF;
      END;
    END IF;
  END LOOP;
  INSERT INTO gerball_tracking_private.cohorts(id, rule_version, league_code, capture_date,
    collection_date, collection_checked_at, collection_status, source_fixture_count,
    fixture_count, skipped_started, mode, input_sha256)
  VALUES (v_id, v_rule.version, p_league, v_today, v_today, v_collection.checked_at,
    v_collection.status, v_fixture_count, 0, 0, p_mode, repeat('0',64));
  RETURN jsonb_build_object('league_code', p_league, 'status', 'recorded', 'cohort_id', v_id,
    'fixture_count', (SELECT fixture_count FROM gerball_tracking_private.cohorts WHERE id = v_id));
END
$function$;

CREATE FUNCTION gerball_tracking_private.capture_daily(p_mode text DEFAULT 'scheduled')
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_league text;
  v_result jsonb;
  v_results jsonb := '[]'::jsonb;
  v_local timestamp := clock_timestamp() AT TIME ZONE 'Europe/London';
  v_success integer;
BEGIN
  IF p_mode IS NULL OR p_mode NOT IN ('scheduled','bootstrap') THEN
    RAISE EXCEPTION 'invalid_capture_mode' USING ERRCODE = '22023';
  END IF;
  IF p_mode = 'scheduled' AND (extract(hour FROM v_local) <> 12 OR extract(minute FROM v_local) NOT IN (15,20,25)) THEN
    RETURN jsonb_build_object('status', 'outside_capture_window');
  END IF;
  FOR v_league IN SELECT jsonb_object_keys(specification->'leagues') FROM gerball_tracking_private.rule_versions
    WHERE version = 'ppg_last5_dates_050_v1' ORDER BY 1 LOOP
    BEGIN
      v_result := gerball_tracking_private.capture_league(v_league, p_mode);
    EXCEPTION WHEN OTHERS THEN
      v_result := jsonb_build_object('league_code', v_league, 'status', 'error',
        'reason', 'Capture failed; existing records were preserved.', 'sqlstate', SQLSTATE);
    END;
    v_results := v_results || jsonb_build_array(v_result);
  END LOOP;
  SELECT count(*)::integer INTO v_success FROM jsonb_array_elements(v_results) AS r
    WHERE r->>'status' IN ('recorded','already_recorded');
  v_result := jsonb_build_object('status', CASE WHEN v_success = jsonb_array_length(v_results) THEN 'complete'
      WHEN v_success > 0 THEN 'partial' ELSE 'failed' END,
    'mode', p_mode, 'leagues', v_results);
  INSERT INTO gerball_tracking_private.operation_runs(operation, details) VALUES ('capture', v_result);
  RETURN v_result;
END
$function$;

-- Pure result classification makes the matching rules independently testable.
-- Candidates are stored match rows, never an external results or odds feed.
CREATE FUNCTION gerball_tracking_private.evaluate_result(p_fixture jsonb, p_candidates jsonb)
RETURNS jsonb LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_count integer;
  v_match jsonb;
  v_empty jsonb := '{"status":"pending","reason":"awaiting_import","match_id":null,"source":null,"imported_at":null,"home_goals":null,"away_goals":null,"full_time_result":null}'::jsonb;
  v_home integer;
  v_away integer;
  v_result text;
BEGIN
  IF p_fixture#>>'{home,canonical_name}' IS NULL OR p_fixture#>>'{away,canonical_name}' IS NULL THEN
    RETURN v_empty || '{"status":"review","reason":"unmatched_teams"}'::jsonb;
  END IF;
  IF jsonb_typeof(p_candidates) IS DISTINCT FROM 'array' THEN
    RETURN v_empty || '{"status":"review","reason":"invalid_result_payload"}'::jsonb;
  END IF;
  SELECT count(*)::integer, (jsonb_agg(c))->0 INTO v_count, v_match
  FROM jsonb_array_elements(p_candidates) AS c
  WHERE c->>'league' = p_fixture->>'league_code'
    AND c->>'season' = p_fixture->>'season'
    AND c->>'match_date' = p_fixture->>'fixture_date'
    AND c->>'home_team' = p_fixture#>>'{home,canonical_name}'
    AND c->>'away_team' = p_fixture#>>'{away,canonical_name}';
  IF v_count = 0 THEN RETURN v_empty; END IF;
  IF v_count > 1 THEN RETURN v_empty || '{"status":"review","reason":"ambiguous_result"}'::jsonb; END IF;
  IF v_match->>'source' IS DISTINCT FROM 'football-data.co.uk' THEN
    RETURN v_empty || '{"status":"review","reason":"unexpected_source"}'::jsonb;
  END IF;
  IF v_match->>'imported_at' IS NULL OR p_fixture->>'recorded_at' IS NULL
    OR (v_match->>'imported_at')::timestamptz <= (p_fixture->>'recorded_at')::timestamptz THEN
    RETURN v_empty || '{"status":"review","reason":"result_predates_capture"}'::jsonb;
  END IF;
  IF jsonb_typeof(v_match->'home_goals') IS DISTINCT FROM 'number'
    OR jsonb_typeof(v_match->'away_goals') IS DISTINCT FROM 'number'
    OR (v_match->>'home_goals') !~ '^[0-9]{1,9}$'
    OR (v_match->>'away_goals') !~ '^[0-9]{1,9}$' THEN
    RETURN v_empty || '{"status":"review","reason":"inconsistent_result"}'::jsonb;
  END IF;
  v_home := (v_match->>'home_goals')::integer;
  v_away := (v_match->>'away_goals')::integer;
  v_result := CASE WHEN v_home > v_away THEN 'H' WHEN v_home < v_away THEN 'A' ELSE 'D' END;
  IF v_match->>'full_time_result' IS DISTINCT FROM v_result THEN
    RETURN v_empty || '{"status":"review","reason":"inconsistent_result"}'::jsonb;
  END IF;
  RETURN jsonb_build_object('status','settled','reason','exact_imported_result',
    'match_id',(v_match->>'id')::bigint,'source',v_match->>'source',
    'imported_at',(v_match->>'imported_at')::timestamptz,
    'home_goals',v_home,'away_goals',v_away,'full_time_result',v_result);
EXCEPTION WHEN OTHERS THEN
  RETURN v_empty || '{"status":"review","reason":"invalid_result_payload"}'::jsonb;
END
$function$;

CREATE FUNCTION gerball_tracking_private.reconcile_results()
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_row record;
  v_result jsonb;
  v_hash text;
  v_last_hash text;
  v_revision integer;
  v_checked integer := 0;
  v_appended integer := 0;
  v_started_at timestamptz := clock_timestamp();
BEGIN
  IF NOT pg_try_advisory_xact_lock(hashtextextended('gerball-tracking-reconcile',0)) THEN
    RETURN jsonb_build_object('status','already_running');
  END IF;
  FOR v_row IN
    SELECT o.*, COALESCE(c.candidates,'[]'::jsonb) AS candidates
    FROM gerball_tracking_private.observations AS o
    LEFT JOIN LATERAL (
      SELECT jsonb_agg(jsonb_build_object('id',m.id,'league',m.league,'season',m.season,
        'match_date',m.match_date,'home_team',m.home_team,'away_team',m.away_team,
        'home_goals',m.home_goals,'away_goals',m.away_goals,'full_time_result',m.full_time_result,
        'source',m.source,'imported_at',m.imported_at) ORDER BY m.id) AS candidates
      FROM public.matches AS m
      WHERE m.league = o.league_code AND m.season = o.season AND m.match_date = o.fixture_date
        AND m.home_team = o.fixture#>>'{home,canonical_name}'
        AND m.away_team = o.fixture#>>'{away,canonical_name}'
    ) AS c ON true
    WHERE o.kickoff_at <= v_started_at - interval '3 hours'
    ORDER BY o.id
  LOOP
    v_checked := v_checked + 1;
    v_result := gerball_tracking_private.evaluate_result(v_row.fixture || jsonb_build_object(
      'season',v_row.season,'fixture_date',v_row.fixture_date,'recorded_at',v_row.recorded_at),v_row.candidates);
    v_hash := encode(extensions.digest((v_result - 'imported_at')::text,'sha256'),'hex');
    SELECT result_sha256,revision INTO v_last_hash,v_revision
      FROM gerball_tracking_private.result_revisions
      WHERE observation_id = v_row.id ORDER BY revision DESC LIMIT 1;
    IF v_last_hash IS DISTINCT FROM v_hash THEN
      INSERT INTO gerball_tracking_private.result_revisions(observation_id,revision,status,reason,
        match_id,source,imported_at,home_goals,away_goals,full_time_result,result_sha256,correction_reason)
      VALUES (v_row.id,1,v_result->>'status',v_result->>'reason',(v_result->>'match_id')::bigint,
        v_result->>'source',(v_result->>'imported_at')::timestamptz,(v_result->>'home_goals')::integer,
        (v_result->>'away_goals')::integer,v_result->>'full_time_result',v_hash,
        CASE WHEN v_revision IS NOT NULL THEN 'Imported result availability or score changed; the previous revision is retained.' END);
      v_appended := v_appended + 1;
    END IF;
  END LOOP;
  v_result := jsonb_build_object('status','complete','checked',v_checked,'appended',v_appended);
  INSERT INTO gerball_tracking_private.operation_runs(operation,details) VALUES ('reconcile',v_result);
  RETURN v_result;
END
$function$;

-- Rank before splitting into phases. Repeated daily records and duplicate provider
-- IDs for one exact canonical fixture each contribute a single observation.
CREATE VIEW gerball_tracking_private.qualified_representatives WITH (security_invoker = true) AS
WITH event_ranked AS (
  SELECT o.id, o.rule_version, o.league_code, o.event_id, o.recorded_at, o.fixture_date, o.season,
    o.fixture#>>'{home,canonical_name}' AS home_team, o.fixture#>>'{away,canonical_name}' AS away_team,
    m.key AS market,
    row_number() OVER (PARTITION BY o.rule_version,o.league_code,o.event_id,m.key ORDER BY o.recorded_at,o.id) AS event_rank
  FROM gerball_tracking_private.observations AS o
  CROSS JOIN LATERAL jsonb_each(o.fixture->'markets') AS m
  WHERE m.key IN ('H','D','A') AND m.value->>'status' = 'match'
), event_first AS (
  SELECT * FROM event_ranked WHERE event_rank = 1
), mapped AS (
  SELECT e.*, first_value(id) OVER (PARTITION BY rule_version,league_code,season,fixture_date,home_team,away_team,market
    ORDER BY recorded_at,id) AS representative_id
  FROM event_first AS e
)
SELECT rule_version,league_code,event_id,market,id AS event_first_id,representative_id FROM mapped;
REVOKE ALL ON gerball_tracking_private.qualified_representatives FROM PUBLIC,anon,authenticated;
GRANT SELECT ON gerball_tracking_private.qualified_representatives TO service_role;

CREATE FUNCTION public.gerball_recorded_screens(p_league text DEFAULT 'E0',p_capture_date date DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY INVOKER SET search_path = ''
AS $function$
DECLARE
  v_rule gerball_tracking_private.rule_versions%ROWTYPE;
  v_cohort gerball_tracking_private.cohorts%ROWTYPE;
  v_today date := (statement_timestamp() AT TIME ZONE 'Europe/London')::date;
  v_sport text;
  v_today_cohort gerball_tracking_private.cohorts%ROWTYPE;
  v_collection_status text;
  v_today_status text;
  v_today_reason text;
  v_latest_capture jsonb;
  v_summary jsonb;
  v_records jsonb;
  v_dates jsonb;
BEGIN
  SELECT * INTO STRICT v_rule FROM gerball_tracking_private.rule_versions WHERE version = 'ppg_last5_dates_050_v1';
  v_sport := v_rule.specification->'leagues'->>p_league;
  IF v_sport IS NULL THEN RAISE EXCEPTION 'invalid_recorded_screen_league' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_cohort FROM gerball_tracking_private.cohorts
    WHERE rule_version = v_rule.version AND league_code = p_league
      AND (p_capture_date IS NULL OR capture_date = p_capture_date)
    ORDER BY capture_date DESC LIMIT 1;
  SELECT * INTO v_today_cohort FROM gerball_tracking_private.cohorts
    WHERE rule_version = v_rule.version AND league_code = p_league AND capture_date = v_today;
  SELECT status INTO v_collection_status FROM public.gerball_odds_league_runs
    WHERE collection_date = v_today AND sport_key = v_sport;
  SELECT entry INTO v_latest_capture FROM gerball_tracking_private.operation_runs AS r
    CROSS JOIN LATERAL jsonb_array_elements(r.details->'leagues') AS entry
    WHERE r.operation = 'capture' AND r.operation_date = v_today AND entry->>'league_code' = p_league
    ORDER BY r.recorded_at DESC,r.id DESC LIMIT 1;
  v_today_status := CASE WHEN v_today_cohort.id IS NOT NULL THEN 'recorded'
    WHEN v_latest_capture->>'status' IN ('error','implementation_changed') THEN v_latest_capture->>'status'
    WHEN v_collection_status IN ('completed','inactive') THEN 'pending_capture' ELSE 'waiting_for_collection' END;
  v_today_reason := CASE v_today_status WHEN 'recorded' THEN 'A sealed cohort is stored for today.'
    WHEN 'pending_capture' THEN 'Collection is ready; the daily recording is pending.'
    WHEN 'waiting_for_collection' THEN 'A completed same-day league collection is required.'
    ELSE COALESCE(v_latest_capture->>'reason','Recording requires review.') END;

  WITH representatives AS MATERIALIZED (
    SELECT DISTINCT q.representative_id,q.market FROM gerball_tracking_private.qualified_representatives AS q
      WHERE q.rule_version = v_rule.version AND q.league_code = p_league
  ), current_results AS (
    SELECT o.id,o.phase,r.market,s.status,s.full_time_result
    FROM representatives AS r JOIN gerball_tracking_private.observations AS o ON o.id = r.representative_id
    LEFT JOIN LATERAL (SELECT status,full_time_result FROM gerball_tracking_private.result_revisions
      WHERE observation_id = o.id ORDER BY revision DESC LIMIT 1) AS s ON true
  ), groups AS (
    SELECT m.market,p.phase FROM (VALUES ('H'::text),('D'::text),('A'::text)) AS m(market)
      CROSS JOIN (VALUES ('calibration'::text),('post_boundary'::text)) AS p(phase)
  ), metrics AS (
    SELECT g.market,g.phase,jsonb_build_object(
      'fixtures',count(c.id),'settled',count(c.id) FILTER (WHERE c.status = 'settled'),
      'matched',count(c.id) FILTER (WHERE c.status = 'settled' AND c.full_time_result = g.market),
      'not_matched',count(c.id) FILTER (WHERE c.status = 'settled' AND c.full_time_result <> g.market),
      'pending',count(c.id) FILTER (WHERE c.status IS NULL OR c.status = 'pending'),
      'review',count(c.id) FILTER (WHERE c.status = 'review'),
      'match_rate_pct',round(100.0 * count(c.id) FILTER (WHERE c.status = 'settled' AND c.full_time_result = g.market)
        / NULLIF(count(c.id) FILTER (WHERE c.status = 'settled'),0),2)
    ) AS metric FROM groups AS g LEFT JOIN current_results AS c ON c.market = g.market AND c.phase = g.phase
    GROUP BY g.market,g.phase
  ), market_metrics AS (
    SELECT market,jsonb_object_agg(phase,metric) AS phases FROM metrics GROUP BY market
  ) SELECT jsonb_object_agg(market,phases) INTO v_summary FROM market_metrics;

  SELECT COALESCE(jsonb_agg(jsonb_build_object('capture_date',c.capture_date,'captured_at',c.captured_at,
    'fixture_count',c.fixture_count,'mode',c.mode) ORDER BY c.capture_date DESC),'[]'::jsonb) INTO v_dates
  FROM (SELECT * FROM gerball_tracking_private.cohorts WHERE rule_version = v_rule.version AND league_code = p_league
    ORDER BY capture_date DESC LIMIT 90) AS c;

  WITH representatives AS MATERIALIZED (
    SELECT * FROM gerball_tracking_private.qualified_representatives
      WHERE rule_version = v_rule.version AND league_code = p_league
  )
  SELECT COALESCE(jsonb_agg(o.fixture || jsonb_build_object(
    'id',o.id,'rule_version',o.rule_version,'capture_date',v_cohort.capture_date,'recorded_at',o.recorded_at,
    'kickoff_at',o.kickoff_at,'fixture_date',o.fixture_date,'season',o.season,'phase',o.phase,'input_sha256',o.input_sha256,
    'first_qualifying',f.first_qualifying,
    'result',COALESCE(s.result,jsonb_build_object('status','pending','reason','awaiting_result',
      'revision',0,'recorded_at',NULL,'match_id',NULL,'source',NULL,'imported_at',NULL,
      'home_goals',NULL,'away_goals',NULL,'full_time_result',NULL,'correction_reason',NULL))
      || jsonb_build_object('history',COALESCE(h.history,'[]'::jsonb))
  ) ORDER BY o.kickoff_at,o.event_id),'[]'::jsonb) INTO v_records
  FROM gerball_tracking_private.observations AS o
  LEFT JOIN LATERAL (
    SELECT jsonb_object_agg(m.market,CASE WHEN first_o.id IS NULL THEN 'null'::jsonb ELSE
      jsonb_build_object('record_id',first_o.id,'capture_date',first_c.capture_date) END) AS first_qualifying
    FROM (VALUES ('H'::text),('D'::text),('A'::text)) AS m(market)
    LEFT JOIN representatives AS q ON q.rule_version = o.rule_version
      AND q.league_code = o.league_code AND q.event_id = o.event_id AND q.market = m.market
    LEFT JOIN gerball_tracking_private.observations AS first_o ON first_o.id = q.representative_id
    LEFT JOIN gerball_tracking_private.cohorts AS first_c ON first_c.id = first_o.cohort_id
  ) AS f ON true
  LEFT JOIN LATERAL (
    SELECT to_jsonb(r) - 'observation_id' - 'result_sha256' AS result
    FROM gerball_tracking_private.result_revisions AS r WHERE r.observation_id = o.id ORDER BY r.revision DESC LIMIT 1
  ) AS s ON true
  LEFT JOIN LATERAL (
    SELECT jsonb_agg(to_jsonb(r) - 'observation_id' - 'result_sha256' ORDER BY r.revision) AS history
    FROM gerball_tracking_private.result_revisions AS r WHERE r.observation_id = o.id
  ) AS h ON true
  WHERE o.cohort_id = v_cohort.id;

  RETURN jsonb_build_object('status','ok','version','recorded_screens_v1','rule_version',v_rule.version,
    'generated_at',statement_timestamp(),'timezone','Europe/London','league_code',p_league,
    'evaluation_start',v_rule.evaluation_start,'method',(v_rule.specification - 'leagues')
      || jsonb_build_object('rule_frozen_at',v_rule.frozen_at,'implementation_sha256',v_rule.implementation_sha256,
        'source_commit',v_rule.source_commit),
    'coverage',jsonb_build_object('today',jsonb_build_object('date',v_today,'status',v_today_status,
      'collection_status',v_collection_status,'captured_at',v_today_cohort.captured_at,'reason',v_today_reason),
      'captured_leagues_today',(SELECT count(*) FROM gerball_tracking_private.cohorts
        WHERE rule_version = v_rule.version AND capture_date = v_today),
      'expected_leagues',18,'latest_reconciliation_at',(SELECT max(recorded_at)
        FROM gerball_tracking_private.operation_runs WHERE operation = 'reconcile')),
    'available_dates',v_dates,'cohort',CASE WHEN v_cohort.id IS NULL THEN NULL ELSE to_jsonb(v_cohort) END,
    'summary',v_summary,'records',v_records);
END
$function$;

REVOKE ALL ON ALL FUNCTIONS IN SCHEMA gerball_tracking_private FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON FUNCTION public.gerball_recorded_screens(text,date) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.gerball_recorded_screens(text,date) TO service_role;

